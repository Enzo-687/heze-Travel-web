def detect_region(title):
    """根据名称推测所在区县"""
    for region, keywords in REGION_KEYWORDS.items():
        for kw in keywords:
            if kw in title:
                return region
    return "菏泽市"


def detect_spot_type(title):
    """根据名称推测景点类型"""
    for keywords, spot_type, type_detail in SPOT_TYPE_KEYWORDS:
        if any(k in title for k in keywords):
            return spot_type, type_detail
    return "人文景观", "历史文化景点"


